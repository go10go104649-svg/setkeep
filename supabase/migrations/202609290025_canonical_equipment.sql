-- Shared exercise knowledge without changing any equipment / inventory identity.
begin;
create function public.canonical_equipment_key(value text) returns text
language sql immutable strict set search_path = '' as $$
  select regexp_replace(lower(normalize(value, NFKC)), '[[:space:]・]', '', 'g');
$$;
create table public.canonical_equipment (
  id text primary key, name text not null,
  catalog_status text not null default 'supported'
    check (catalog_status in ('supported', 'exercise_not_in_catalog')),
  review_basis text not null
);
-- Exact, reviewed signatures generate suggestions for future imports; they never
-- auto-approve a new equipment row. Manufacturer/model/load differences remain visible.
create table public.canonical_equipment_matchers (
  id bigint generated always as identity primary key,
  canonical_id text not null references public.canonical_equipment(id),
  name_key text not null, category text not null, load_type text not null,
  manufacturer text not null default '', model text not null default '',
  required_direct_ids text[] not null default '{}',
  unique(canonical_id, name_key, category, load_type, manufacturer, model)
);
create index canonical_match_name_idx on public.canonical_equipment_matchers(name_key, category, load_type);
create table public.equipment_canonical_mapping (
  equipment_id text not null references public.equipment(id),
  canonical_id text not null references public.canonical_equipment(id),
  matcher_id bigint not null references public.canonical_equipment_matchers(id),
  reviewed_at timestamptz not null default now(),
  review_basis text not null,
  primary key(equipment_id, canonical_id)
);
create index equipment_canonical_reverse_idx on public.equipment_canonical_mapping(canonical_id);
create table public.canonical_equipment_exercise_mapping (
  canonical_id text not null references public.canonical_equipment(id),
  exercise_id text not null, rationale text not null,
  primary key(canonical_id, exercise_id)
);
create table public.canonical_equipment_rules (
  id text primary key, exercise_id text not null, rationale text not null
);
create table public.canonical_equipment_rule_items (
  rule_id text not null references public.canonical_equipment_rules(id) on delete cascade,
  canonical_id text not null references public.canonical_equipment(id),
  primary key(rule_id, canonical_id)
);
create index canonical_rule_items_equipment_idx on public.canonical_equipment_rule_items(canonical_id);
do $$ declare t text; begin
  foreach t in array array['canonical_equipment', 'canonical_equipment_matchers',
    'equipment_canonical_mapping', 'canonical_equipment_exercise_mapping',
    'canonical_equipment_rules', 'canonical_equipment_rule_items'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('create policy reference_read on public.%I for select to anon, authenticated using(true)', t);
  end loop;
end $$;

create view public.equipment_canonical_matches with (security_invoker = true) as
  select e.id equipment_id, m.canonical_id, m.id matcher_id
  from public.equipment e join public.canonical_equipment_matchers m
    on public.canonical_equipment_key(e.name) = m.name_key
    and public.canonical_equipment_key(e.normalized_name) = m.name_key
    and e.category = m.category and e.load_type = m.load_type
    and coalesce(e.manufacturer, '') = m.manufacturer
    and coalesce(e.model, '') = m.model
  where not exists (
    select 1 from unnest(m.required_direct_ids) x(exercise_id)
    where not exists (select 1 from public.equipment_exercise_mapping d
      where d.equipment_id=e.id and d.exercise_id=x.exercise_id)
  );
create view public.equipment_canonical_candidates with (security_invoker = true) as
  select x.*, 'review_required'::text status
  from public.equipment_canonical_matches x where not exists (
    select 1 from public.equipment_canonical_mapping m
    where m.equipment_id=x.equipment_id and m.canonical_id=x.canonical_id);
-- Invalidate an old approval if the equipment's identifying metadata changes.
create view public.equipment_canonical_memberships with (security_invoker = true) as
  select m.equipment_id, m.canonical_id from public.equipment_canonical_mapping m
  join public.equipment_canonical_matches x on x.equipment_id=m.equipment_id
    and x.canonical_id=m.canonical_id and x.matcher_id=m.matcher_id;
create view public.equipment_resolved_exercise_mapping with (security_invoker = true) as
  select equipment_id, exercise_id from public.equipment_exercise_mapping
  union
  select m.equipment_id, x.exercise_id from public.equipment_canonical_memberships m
    join public.canonical_equipment_exercise_mapping x on x.canonical_id=m.canonical_id;
grant select on public.equipment_canonical_matches, public.equipment_canonical_candidates,
  public.equipment_canonical_memberships, public.equipment_resolved_exercise_mapping to anon, authenticated;

-- One evaluator serves stores AND the owner's private place equipment.
create or replace function public.equipment_exercise_evidence(selected_equipment_ids text[])
returns table(exercise_id text, equipment_ids text[], equipment_names text[], rule_id text)
language sql stable security invoker set search_path='' as $$
  with usable as materialized (
    select e.id, coalesce(e.display_name,e.name) name from public.equipment e
    where e.id=any(selected_equipment_ids)
  ), direct as (
    select m.exercise_id, array[u.id], array[u.name], null::text
    from usable u join public.equipment_resolved_exercise_mapping m on m.equipment_id=u.id
  ), legacy_combinations as (
    select r.exercise_id, array_agg(i.equipment_id order by i.equipment_id),
      array_agg(u.name order by i.equipment_id), r.id
    from public.exercise_equipment_rules r
    join public.exercise_equipment_rule_items i on i.rule_id=r.id
    left join usable u on u.id=i.equipment_id
    group by r.id,r.exercise_id having count(*)=count(u.id)
  ), capabilities as materialized (
    select m.canonical_id, min(u.id) equipment_id
    from usable u join public.equipment_canonical_memberships m on m.equipment_id=u.id
    group by m.canonical_id
  ), canonical_combinations as (
    select r.exercise_id, array_agg(u.id order by i.canonical_id),
      array_agg(u.name order by i.canonical_id), r.id
    from public.canonical_equipment_rules r
    join public.canonical_equipment_rule_items i on i.rule_id=r.id
    left join capabilities c on c.canonical_id=i.canonical_id
    left join usable u on u.id=c.equipment_id
    group by r.id,r.exercise_id having count(*)=count(u.id)
  ) select * from direct union select * from legacy_combinations
    union select * from canonical_combinations;
$$;

create function public.gym_equipment_reference(target_equipment_id text) returns jsonb
language sql stable security invoker set search_path='' as $$
  select to_jsonb(e) || jsonb_build_object(
    'equipment_exercise_mapping', coalesce((select jsonb_agg(jsonb_build_object('exercise_id', m.exercise_id))
      from public.equipment_resolved_exercise_mapping m where m.equipment_id=e.id), '[]'::jsonb),
    'exercise_equipment_rule_items', coalesce((select jsonb_agg(jsonb_build_object('rule_id', x.rule_id)) from (
      select i.rule_id from public.exercise_equipment_rule_items i where i.equipment_id=e.id
      union select i.rule_id from public.equipment_canonical_memberships m
        join public.canonical_equipment_rule_items i on i.canonical_id=m.canonical_id
        where m.equipment_id=e.id
    ) x), '[]'::jsonb)) from public.equipment e where e.id=target_equipment_id;
$$;
create or replace function public.gym_store_detail(target_store_id text) returns jsonb
language sql stable security invoker set search_path='' as $$
  select jsonb_build_object(
    'store', (select to_jsonb(s)||jsonb_build_object('chain_name',c.name)
      from public.gym_stores s join public.gym_chains c on c.id=s.chain_id where s.id=target_store_id),
    'equipment', coalesce((select jsonb_agg(to_jsonb(g)||jsonb_build_object(
      'equipment', public.gym_equipment_reference(e.id)) order by e.category,e.name,e.id)
      from public.gym_store_equipment g join public.equipment e on e.id=g.equipment_id
      where g.store_id=target_store_id and g.presence_status='present'), '[]'::jsonb),
    'evidence', coalesce((select jsonb_agg(to_jsonb(x))
      from public.gym_store_exercise_evidence(target_store_id) x), '[]'::jsonb));
$$;
create function public.gym_store_equipment_page(target_store_id text, page_offset integer default 0)
returns setof jsonb language sql stable security invoker set search_path='' as $$
  select to_jsonb(g)||jsonb_build_object('equipment',public.gym_equipment_reference(g.equipment_id))
  from public.gym_store_equipment g
  where g.store_id=target_store_id and g.presence_status='present'
  order by g.equipment_id limit 50 offset greatest(0,least(page_offset,100000));
$$;
create or replace function public.search_equipment(search_query text default '', page_offset integer default 0)
returns setof jsonb language sql stable security invoker set search_path='' as $$
  select jsonb_build_object('equipment',public.gym_equipment_reference(e.id))
  from public.equipment e
  where public.gym_search_text(concat_ws(' ',e.name,e.display_name,e.manufacturer,e.model,array_to_string(e.aliases,' ')))
    like '%'||public.gym_search_text(search_query)||'%'
  order by e.name,e.id limit 30 offset greatest(page_offset,0);
$$;
revoke all on function public.canonical_equipment_key(text), public.gym_equipment_reference(text),
  public.gym_store_equipment_page(text,integer) from public;
grant execute on function public.canonical_equipment_key(text), public.gym_equipment_reference(text),
  public.gym_store_equipment_page(text,integer) to anon,authenticated;

